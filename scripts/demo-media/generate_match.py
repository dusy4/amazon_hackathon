def nearest_player(team, p, exclude=None, outfield=True):
    best, bd = None, 9
    for num in ROSTER[team]:
        if num == exclude or (outfield and num == 1):
            continue
        bx, by = base_pos(team, num)
        d = (bx - p[0]) ** 2 + (by - p[1]) ** 2
        if d < bd:
            best, bd = num, d
    return best


def filler(t0, t1, team, p0, p1, first=None):
    """Plausible passing sequence for `team` moving the ball from p0 to p1."""
    t = t0
    cur = first or nearest_player(team, p0)
    pos = p0
    steps = max(2, int((t1 - t0) / 2.2))
    for i in range(steps):
        frac = (i + 1) / steps
        nxt_pt = (p0[0] + (p1[0] - p0[0]) * frac + rng.uniform(-0.04, 0.04),
                  min(0.92, max(0.08, p0[1] + (p1[1] - p0[1]) * frac + rng.uniform(-0.18, 0.18))))
        span = (t1 - t) / (steps - i)
        run_end = (pos[0] + (0.03 if team == HOME else -0.03), pos[1])
        ph(t, t + span * 0.45, "run", team, cur, pos, run_end)
        nxt = nearest_player(team, nxt_pt, exclude=cur)
        if i == steps - 1:
            nxt_pt = p1
        ph(t + span * 0.45, t + span, "pass", team, cur, run_end, nxt_pt, receiver=(team, nxt))
        cur, pos, t = nxt, nxt_pt, t + span
    return cur


