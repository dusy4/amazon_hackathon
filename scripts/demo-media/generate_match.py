SR = 22050


def synth_commentary(tmp):
    lines = [{"i": i, "text": txt, "path": os.path.join(tmp, f"c{i:03d}.wav")} for i, (_, txt) in enumerate(COMMENTARY)]
    jpath = os.path.join(tmp, "lines.json")
    with open(jpath, "w", encoding="utf-8") as f:
        json.dump(lines, f)
    ps = f"""
Add-Type -AssemblyName System.Speech
$s = New-Object System.Speech.Synthesis.SpeechSynthesizer
try {{ $s.SelectVoice('Microsoft David Desktop') }} catch {{}}
$s.Rate = 1
$fmt = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo({SR}, [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen, [System.Speech.AudioFormat.AudioChannel]::Mono)
$lines = Get-Content -Raw -Path '{jpath}' | ConvertFrom-Json
foreach ($l in $lines) {{ $s.SetOutputToWaveFile($l.path, $fmt); $s.Speak($l.text) }}
$s.SetOutputToNull()
"""
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], check=True)
    out = []
    for (start, txt), l in zip(COMMENTARY, lines):
        with wave.open(l["path"]) as w:
            data = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
        out.append((start, txt, data))
    return out


def crowd_track(n):
    r = np.random.default_rng(3)
    white = r.standard_normal(n).astype(np.float32)
    # moving-average low-pass for a crowd-like rumble
    low = np.convolve(white, np.ones(14, dtype=np.float32) / 14, mode="same")
    low /= np.max(np.abs(low)) + 1e-9
    t = np.arange(n) / SR
    env = np.full(n, 0.06, dtype=np.float32)
    for gt, _ in GOAL_TIMES:
        env += 0.32 * np.exp(-np.clip(t - gt, 0, None) / 3.0) * (t >= gt)
    for e in events:
        if e["type"] in ("save", "shot", "yellow_card"):
            st = e["startMs"] / 1000
            env += 0.12 * np.exp(-np.clip(t - st, 0, None) / 1.5) * (t >= st)
    return low * env


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join("data", "content", CONTENT_ID))
    ap.add_argument("--seconds", type=float, default=DURATION, help="render only the first N seconds (debug)")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    dur = min(DURATION, args.seconds)
    n_audio = int(dur * SR)

    with tempfile.TemporaryDirectory() as tmp:
        print("synthesising commentary...", flush=True)
        clips = synth_commentary(tmp)
        voice = np.zeros(n_audio, dtype=np.float32)
        transcript = []
        for i, (start, txt, data) in enumerate(clips):
            a = int(start * SR)
            if a >= n_audio:
                continue
            nxt = clips[i + 1][0] if i + 1 < len(clips) else dur
            end = start + len(data) / SR
            if end > nxt + 0.05:
                print(f"  warn: line {i} overruns next line by {end - nxt:.2f}s: {txt}", file=sys.stderr)
            seg = data[: max(0, n_audio - a)]
            voice[a:a + len(seg)] += seg
            transcript.append({"id": f"tx-{i + 1:03d}", "startMs": int(start * 1000), "endMs": int(min(end, dur) * 1000),
                               "speaker": "commentator", "text": txt})
        print("building crowd bed...", flush=True)
        mix = np.clip(voice * 0.9 + crowd_track(n_audio), -1, 1)
        apath = os.path.join(tmp, "audio.wav")
        with wave.open(apath, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((mix * 32767).astype(np.int16).tobytes())

        vpath = os.path.join(args.out, "match.mp4")
        cmd = ["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}", "-r", str(FPS),
               "-i", "-", "-i", apath, "-c:v", "libx264", "-preset", "veryfast", "-crf", "23", "-pix_fmt", "yuv420p",
               "-g", str(FPS), "-keyint_min", str(FPS), "-c:a", "aac", "-b:a", "128k", "-movflags", "+faststart",
               "-shortest", vpath]
        proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
        nframes = int(dur * FPS)
        for f in range(nframes):
            t = f / FPS
            proc.stdin.write(render_frame(t).tobytes())
            if f % (FPS * 20) == 0:
                print(f"  frame {f}/{nframes}", flush=True)
        proc.stdin.close()
        if proc.wait() != 0:
            raise SystemExit("ffmpeg failed")

    # ---- provider feed: tracking-derived possession + touches, scoreboard states -------------
    possession, touches = [], []
    step = 0.2
    cur, since = None, 6.0
    t = 6.0
    while t < dur:
        m, rep = broadcast_to_match(t)
        pz = None if rep else possession_at(m)
        if pz != cur:
            if cur:
                possession.append({"startMs": int(since * 1000), "endMs": int(t * 1000), "team": cur[0], "number": cur[1],
                                   "name": name(*cur)})
            if pz:
                touches.append({"ms": int(t * 1000), "team": pz[0], "number": pz[1], "name": name(*pz)})
            cur, since = pz, t
        t = round(t + step, 3)
    scoreboard = []
    prev = None
    for sec in range(6, int(dur)):
        h, a = score_at(sec)
        if (h, a) != prev:
            scoreboard.append({"startMs": sec * 1000, "home": h, "away": a, "text": f"HCFC {h} - {a} NGU"})
            prev = (h, a)
    for i, s in enumerate(scoreboard):
        s["endMs"] = scoreboard[i + 1]["startMs"] if i + 1 < len(scoreboard) else int(dur * 1000)

    provider = {
        "contentId": CONTENT_ID, "title": TITLE, "kind": "sports_match", "sport": "football",
        "durationMs": int(dur * 1000), "media": "match.mp4",
        "source": "synthetic footage rendered by scripts/demo-media/generate_match.py (owned, no third-party rights)",
        "teams": [{"id": k, **{kk: vv for kk, vv in v.items() if kk in ('name', 'short')}, "side": "home" if k == HOME else "away"} for k, v in TEAMS.items()],
        "roster": [{"team": tm, "number": n, "name": nm, "position": pos} for tm in ROSTER for n, (nm, pos) in ROSTER[tm].items()],
        "events": [e for e in events if e["startMs"] < dur * 1000],
        "replays": [r for r in replays if r["startMs"] < dur * 1000],
        "scoreboard": scoreboard,
        "possession": possession,
        "touches": touches,
        "matchClock": {"broadcastDurationMs": int(DURATION * 1000), "matchMinutes": 90},
    }
    with open(os.path.join(args.out, "provider.json"), "w", encoding="utf-8") as f:
        json.dump(provider, f, indent=1)
    with open(os.path.join(args.out, "commentary.json"), "w", encoding="utf-8") as f:
        json.dump({"contentId": CONTENT_ID, "source": "commentary script synthesised with Windows SAPI TTS (measured line timings)",
                   "lines": transcript}, f, indent=1)
    print(f"done: {vpath}, {len(events)} events, {len(touches)} touches, {len(transcript)} commentary lines")


if __name__ == "__main__":
    main()
