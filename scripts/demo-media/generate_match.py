def ease(u):
    return u * u * (3 - 2 * u)


def phase_at(m):
    for p in phases:
        if p["t0"] <= m < p["t1"]:
            return p
    return phases[-1]


def ball_at(m):
    p = phase_at(m)
    u = 0 if p["t1"] == p["t0"] else min(1, max(0, (m - p["t0"]) / (p["t1"] - p["t0"])))
    if p["kind"] in ("run", "hold", "net"):
        u = ease(u) if p["kind"] == "run" else u
    x = p["p0"][0] + (p["p1"][0] - p["p0"][0]) * u
    y = p["p0"][1] + (p["p1"][1] - p["p0"][1]) * u
    # ball height arc for passes/shots shown as size
    lift = math.sin(math.pi * u) if p["kind"] in ("pass",) and (p["t1"] - p["t0"]) > 1.5 else 0
    return x, y, lift, p, u


def player_pos(team, num, m):
    bx, by, _, p, u = ball_at(m)
    x0, y0 = base_pos(team, num)
    if num == 1:
        x = x0 + (0.02 if team == HOME else -0.02) * (1 if (bx < 0.3 if team == HOME else bx > 0.7) else 0)
        y = 0.5 + (by - 0.5) * 0.25
    else:
        shift = (bx - 0.5) * 0.55
        x = x0 + shift
        y = y0 + (by - 0.5) * 0.22
        x += 0.012 * math.sin(m * 0.9 + num * 1.7 + (0 if team == HOME else 2))
        y += 0.012 * math.cos(m * 0.7 + num * 2.3 + (1 if team == HOME else 0))
    # carrier sits at the ball
    if p["team"] == team and p["num"] == num and p["kind"] in ("run", "hold", "shot", "pass"):
        if p["kind"] in ("run", "hold") or u < 0.15:
            off = -0.012 if team == HOME else 0.012
            src = p["p0"] if p["kind"] in ("shot", "pass") else (bx, by)
            return src[0] + off, src[1] + 0.004
    # receiver runs onto the pass
    if p["receiver"] and p["receiver"] == (team, num):
        tx, ty = p["p1"]
        x = x + (tx - x) * ease(u)
        y = y + (ty - y) * ease(u)
    # celebrations
    for (c0, c1, cteam, scorer, cpt) in CELEBRATIONS:
        if c0 <= m < c1 and team == cteam and num != 1:
            k = ease(min(1, (m - c0) / 2.0))
            jitter = 0.03 if num != scorer else 0
            tx = cpt[0] + jitter * math.cos(num * 2.1)
            ty = cpt[1] + jitter * math.sin(num * 2.1)
            x, y = x + (tx - x) * k, y + (ty - y) * k
    if num != 1 and not any(c0 <= m < c1 for (c0, c1, *_r) in CELEBRATIONS):
        x = min(0.95, max(0.05, x))
    return min(1.02, max(-0.02, x)), min(0.98, max(0.02, y))


def possession_at(m):
    p = phase_at(m)
    if p["kind"] == "net":
        return None
    return p["team"], p["num"]


# ----------------------------------------------------------------------------------------------
# Broadcast time -> match time (replays re-render earlier match time in slow motion)
# ----------------------------------------------------------------------------------------------
def broadcast_to_match(t):
    for r in replays:
        if r["startMs"] / 1000 <= t < r["endMs"] / 1000:
            u = (t - r["startMs"] / 1000) / ((r["endMs"] - r["startMs"]) / 1000)
            return r["sourceStartMs"] / 1000 + u * (r["sourceEndMs"] - r["sourceStartMs"]) / 1000, r
    return t, None


def score_at(t):
    h = a = 0
    for gt, g in GOAL_TIMES:
        if t >= gt + 0.5:
            h, a = g["score"]["home"], g["score"]["away"]
    return h, a


def clock_at(t):
    secs = int(t / DURATION * 90 * 60)
    return f"{secs // 60:02d}:{secs % 60:02d}"


